"""
fill_table_stein.py
===================
Turn stein_smoothing_table.py output into the LaTeX table, so results never
have to be retyped.

Same role as fill_table3.py / fill_table4_resnet.py, for the Stein-path
analogue of Table 7: rows are (scenario, codec), column groups are the
smoothing scale sigma, and the paper's operating point sigma = 0.05 is
highlighted.

Usage
-----
  python fill_table_stein.py \
      --run outputs/stein_smoothing/resnet_topk \
      --run outputs/stein_smoothing/resnet_quant \
      --run outputs/stein_smoothing/resnet_llmint8 \
      --out ../MobiHoc_2026/tables/stein_smoothing_table.tex

  # print to stdout instead of writing
  python fill_table_stein.py --run outputs/stein_smoothing/resnet_topk

  # different metric set
  python fill_table_stein.py --run ... --metrics rmse_debiased,regret_mean,rel_sd

A --run may be either the run directory or the JSON file inside it.  Rows come
out in the order the flags are given.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List

# Codec label -> the macro the paper already defines in macros.tex
CODEC_MACRO = {
    "topk": r"\cmpT",
    "quantization": r"\cmpQ",
    "llmint8": r"\cmpIEight",
}

# Task label -> paper macro
TASK_MACRO = {
    "RN56-CF10": r"\taskVisionTwo",
    "FT5-SST2": r"\taskLangSeven",
}

# metric key -> (column header, format string)
METRICS = {
    "rmse":          (r"RMSE", "{:.4f}"),
    "rmse_debiased": (r"RMSE", "{:.4f}"),
    "r2":            (r"$R^2$", "{:.4f}"),
    "r2_debiased":   (r"$R^2$", "{:.4f}"),
    "sd_a":          (r"sd$(A)$", "{:.4f}"),
    "max_abs_bias":  (r"max$|b|$", "{:.4f}"),
    "mean_bias":     (r"bias", "{:+.4f}"),
    "regret_mean":   (r"$\Delta\Phi$", "{:.4f}"),
    "regret_max":    (r"$\Delta\Phi^{\max}$", "{:.4f}"),
    "acc_gap_mean":  (r"$\Delta A$", "{:+.4f}"),
    "rel_sd":        (r"sd$(\hat g)$", "{:.2f}"),
    "cos_seed":      (r"$\cos$", "{:.2f}"),
    "frac_decision_changed": (r"chg", "{:.2f}"),
}

# Mirrors Table 7 (tab:fitting_acc_speed), minus its inference-latency
# column: a Stein gradient costs 2N forward passes, which is not comparable
# to a single surrogate prediction call.
DEFAULT_METRICS = ["rmse_debiased", "r2_debiased"]

PAPER_SIGMA = 0.05


def load_run(path: Path) -> Dict:
    p = Path(path)
    if p.is_dir():
        p = p / "stein_smoothing_results.json"
    if not p.exists():
        raise FileNotFoundError(f"no results at {p}")
    return json.loads(p.read_text())


def fmt(value, spec: str) -> str:
    if value is None:
        return "--"
    try:
        f = float(value)
    except (TypeError, ValueError):
        return "--"
    if f != f:  # NaN -- undefined (e.g. R^2 with zero residual AND zero variance)
        return "--"
    if f == float("inf"):
        return r"$\infty$"
    if f == float("-inf"):
        return r"$-\infty$"
    return spec.format(f)


def sigma_key(sigmas: List[str], target: float) -> str | None:
    for s in sigmas:
        if abs(float(s) - target) < 1e-12:
            return s
    return None


def build_table(runs: List[Dict], metrics: List[str], label: str,
                caption: str) -> str:
    # Sigma columns come from the first run; every run must agree.
    sigmas = list(runs[0]["rows"].keys())
    for r in runs[1:]:
        if list(r["rows"].keys()) != sigmas:
            raise ValueError(
                f"sigma sets differ: {sigmas} vs {list(r['rows'].keys())}. "
                "Re-run with a common --sigmas.")

    n_m = len(metrics)
    paper_key = sigma_key(sigmas, PAPER_SIGMA)

    col_spec = "ll" + " ".join(["r" * n_m for _ in sigmas])
    lines = [
        r"% GENERATED BY fill_table_stein.py -- do not edit by hand.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\scriptsize",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\textwidth}{!}{%",
        rf"\begin{{tabular}}{{{col_spec}}}",
        r"\toprule",
    ]

    # Header row 1: sigma groups
    head = [r"\multirow{2}{*}{Scenario}", r"\multirow{2}{*}{Codec}"]
    for s in sigmas:
        tag = rf"$\bm{{\sigma={s}}}$" if s == paper_key else rf"$\sigma={s}$"
        head.append(rf"\multicolumn{{{n_m}}}{{c}}{{{tag}}}")
    lines.append(" & ".join(head) + r" \\")

    # cmidrules under each sigma group
    rules = []
    start = 3
    for _ in sigmas:
        rules.append(rf"\cmidrule(lr){{{start}-{start + n_m - 1}}}")
        start += n_m
    lines.append("".join(rules))

    # Header row 2: metric names
    sub = ["", ""]
    for _ in sigmas:
        sub.extend(METRICS[m][0] for m in metrics)
    lines.append(" & ".join(sub) + r" \\")
    lines.append(r"\midrule")

    # Body
    last_scenario = None
    for run in runs:
        scenario = run.get("scenario", "?")
        task = run.get("task", "")
        codec = run.get("compressor", "?")

        if last_scenario is not None and scenario != last_scenario:
            lines.append(r"\midrule")
        # Repeat the scenario label only when it changes, like Table 7 does.
        scen_cell = ""
        if scenario != last_scenario:
            scen_cell = TASK_MACRO.get(task, task.replace("_", r"\_"))
            if scenario:
                scen_cell = rf"{scen_cell} \scriptsize({scenario})"
        last_scenario = scenario

        cells = [scen_cell, CODEC_MACRO.get(codec, rf"\emph{{{codec}}}")]
        for s in sigmas:
            row = run["rows"][s]
            for m in metrics:
                cells.append(fmt(row.get(m), METRICS[m][1]))
        lines.append(" & ".join(cells) + r" \\")

    lines += [r"\bottomrule", r"\end{tabular}%", r"}", r"\end{table*}"]
    return "\n".join(lines) + "\n"


def provenance(runs: List[Dict]) -> str:
    """A comment block so the .tex records how the numbers were produced."""
    out = ["% run provenance:"]
    for r in runs:
        c = r.get("config", {})
        m = r.get("meta", {})
        off = r.get("fast_subset_offset", {})
        out.append(
            f"%   {r.get('task','?'):<10} {r.get('compressor','?'):<13} "
            f"grid={c.get('n_grid')}^{c.get('num_links')} "
            f"draws={c.get('n_draws')} gradN={c.get('grad_N')} "
            f"seeds={c.get('grad_seeds')} "
            f"fast={m.get('fast_eval_images')}img true={m.get('true_eval_images')}img "
            f"cut={m.get('cutpoints')} dev={m.get('device')} "
            f"offset_sd={off.get('sd', float('nan')):.4f}"
        )
    return "\n".join(out) + "\n"


def main():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run", action="append", required=True,
                   help="Run directory or results JSON; repeat for each row.")
    p.add_argument("--out", default="",
                   help="Write LaTeX here; default prints to stdout.")
    p.add_argument("--metrics", default=",".join(DEFAULT_METRICS),
                   help=f"Comma-separated subset of {sorted(METRICS)}")
    p.add_argument("--label", default="tab:stein_smoothing")
    p.add_argument("--caption", default=(
        r"Fidelity of the function the Stein oracle sees. Stein's identity does "
        r"not approximate $A$; it estimates $\nabla \tilde{A}_\sigma$, the "
        r"gradient of the Gaussian-smoothed accuracy "
        r"$\tilde{A}_\sigma(\bm{\eta})=\mathbb{E}_{\bm z}[A(\bm{\eta}+\sigma "
        r"\bm z)]$ -- with hard top-$k$ the kept coordinate set changes only at "
        r"$k=\lceil \eta a\rceil$, so $\nabla A$ does not exist. We therefore "
        r"report the same fit-quality measures as Table~\ref{tab:fitting_acc_speed}, "
        r"RMSE and $R^2$, for $\tilde{A}_\sigma$ against $A$ over the $\bm{\eta}$ "
        r"grid, as a function of the smoothing scale $\sigma$; "
        r"$\bm{\sigma=0.05}$ is the value used in the experiments. The "
        r"inference-latency column of Table~\ref{tab:fitting_acc_speed} has no "
        r"counterpart here: a Stein gradient costs $2N$ forward passes through the "
        r"model rather than a single surrogate prediction call. As in "
        r"Table~\ref{tab:fitting_acc_speed}, $R^2$ is normalised by "
        r"$\mathrm{Var}[A]$ over the grid and is therefore uninformative where $A$ "
        r"is near-constant; $-\infty$ denotes exactly zero variance."))
    args = p.parse_args()

    metrics = [m.strip() for m in args.metrics.split(",") if m.strip()]
    bad = [m for m in metrics if m not in METRICS]
    if bad:
        raise SystemExit(f"unknown metric(s) {bad}; choose from {sorted(METRICS)}")

    runs = [load_run(Path(r)) for r in args.run]
    tex = build_table(runs, metrics, args.label, args.caption) + provenance(runs)

    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(tex)
        print(f"wrote {out}  ({len(runs)} rows, {len(metrics)} metrics x "
              f"{len(runs[0]['rows'])} sigmas)")
    else:
        print(tex)


if __name__ == "__main__":
    main()
